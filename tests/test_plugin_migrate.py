def test_dry_run_plans_without_mutating(repo: Path):
    before = _snapshot(repo, PRODUCT_FILES)
    result = run_migrate(repo)  # no --apply

    assert result["applied"] is False
    assert result["already_migrated"] is False
    # Framework files are still on disk after a dry run.
    assert (repo / "tools" / "product-hook").is_file()
    assert (repo / ".claude" / "skills" / "critic" / "SKILL.md").is_file()
    assert (repo / ".prawduct" / "critic-review.md").is_file()
    # Product files untouched.
    assert _snapshot(repo, PRODUCT_FILES) == before
    # Plan names the framework files.
    assert "tools/product-hook" in result["removed"]
    assert ".prawduct/sync-manifest.json" in result["removed"]


def test_dry_run_plan_is_registry_derived(repo: Path):
    result = run_migrate(repo)
    removed = set(result["removed"])
    # All 7 framework skills + protocol docs + lib + hook in the plan.
