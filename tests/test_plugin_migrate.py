def test_apply_removes_framework_files(repo: Path):
    run_migrate(repo, "--apply")

    assert not (repo / "tools" / "product-hook").exists()
    assert not (repo / "tools" / "lib").exists()  # dir removed when empty
    assert not (repo / ".prawduct" / "sync-manifest.json").exists()
    for doc in ("critic-review", "pr-review", "build-governance"):
        assert not (repo / ".prawduct" / f"{doc}.md").exists()
    for s in FRAMEWORK_SKILLS:
        assert not (repo / ".claude" / "skills" / s).exists()  # whole dir gone


def test_apply_preserves_all_product_files_byte_for_byte(repo: Path):
    # The acceptance contract: zero changes to the NEVER-TOUCH set.
    before = _snapshot(repo, PRODUCT_FILES)
    run_migrate(repo, "--apply")
    after = _snapshot(repo, PRODUCT_FILES)
    assert after == before, "a product file changed during migration"
    # And every product file still exists.
    assert set(after.keys()) == set(before.keys())


def test_product_skill_and_tool_dirs_survive(repo: Path):
    run_migrate(repo, "--apply")
    for s in PRODUCT_SKILLS:
        assert (repo / ".claude" / "skills" / s / "SKILL.md").is_file()
    for t in PRODUCT_TOOLS:
        assert (repo / "tools" / t).is_file()
    # tools/ itself survives (it still holds product scripts).
    assert (repo / "tools").is_dir()


