def run_migrate(project_dir: Path, *flags: str) -> dict:
    """Invoke `bin/prawduct-hook migrate-plugin [flags] --json` as Claude would."""
    home = project_dir.parent / "_home"
    home.mkdir(exist_ok=True)
    env = {
        "HOME": str(home),
        "CLAUDE_PROJECT_DIR": str(project_dir),
        "CLAUDE_PLUGIN_ROOT": str(ROOT),
        "PATH": "/usr/bin:/bin:/usr/sbin:/sbin",
        "PYTHONDONTWRITEBYTECODE": "1",
    }
    proc = subprocess.run(
        [sys.executable, str(HOOK), "migrate-plugin", *flags, "--json"],
        capture_output=True, text=True, env=env, timeout=30,
    )
    assert proc.returncode == 0, f"migrate failed: {proc.stderr}\n{proc.stdout}"
    return json.loads(proc.stdout)


def _snapshot(root: Path, rels: list[str]) -> dict[str, str]:
    out = {}
    for rel in rels:
        p = root / rel
        if p.is_file():
            out[rel] = hashlib.sha256(p.read_bytes()).hexdigest()
    return out


