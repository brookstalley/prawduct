    (root / "tools" / "lib" / "__pycache__").mkdir(parents=True, exist_ok=True)
    (root / "tools" / "lib" / "__pycache__" / "core.pyc").write_bytes(b"\x00bytecode")
    for t in PRODUCT_TOOLS:
        _w(root / "tools" / t, f"# product tool {t}\n")

    # --- .prawduct: framework protocol docs + product state ---
    _w(root / ".prawduct" / "critic-review.md", "framework critic protocol\n")
    _w(root / ".prawduct" / "pr-review.md", "framework pr protocol\n")
    _w(root / ".prawduct" / "build-governance.md", "framework build governance\n")
    _w(root / ".prawduct" / "sync-manifest.json", '{"files": {"tools/product-hook": "abc"}}\n')
    _w(root / ".prawduct" / "project-state.yaml",
       "# Project State\nbacklog_format_version: 2\nviews_enabled: true\n")
    _w(root / ".prawduct" / "learnings.md", "## A learning\nbody\n")
    _w(root / ".prawduct" / "learnings-detail.md", "detail\n")
    _w(root / ".prawduct" / "backlog.md", "# Backlog\n- item\n")
    _w(root / ".prawduct" / "change-log.md", "# Change Log\n")
    _w(root / ".prawduct" / "artifacts" / "build-plan.md", "# Build plan\n- [x] chunk\n")
    _w(root / ".prawduct" / ".critic-findings.json", '{"summary":"ok","findings":[]}\n')

    # --- product source/tests/docs ---
    _w(root / "src" / "app.py", "print('hi')\n")
    _w(root / "tests" / "test_app.py", "def test_x():\n    assert True\n")
    _w(root / "README.md", "# MyProduct\n")
    _w(root / ".gitignore", "__pycache__/\n.prawduct/.critic-findings.json\n")
