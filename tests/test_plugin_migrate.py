def test_settings_mixed_sessionstart_keeps_only_user_group(repo: Path):
    # The hallucinote shape: SessionStart has a prawduct group AND a user group.
    run_migrate(repo, "--apply")
    data = json.loads((repo / ".claude" / "settings.json").read_text())
    ss = data["hooks"]["SessionStart"]
    assert len(ss) == 1, "the prawduct SessionStart group must be removed, the user group kept"
    assert "session-start.sh" in ss[0]["hooks"][0]["command"]
    assert all("product-hook" not in g["hooks"][0]["command"] for g in ss)


def test_settings_transformed_and_user_keys_preserved(repo: Path):
    run_migrate(repo, "--apply")
    data = json.loads((repo / ".claude" / "settings.json").read_text())

    # Framework banner removed; the prawduct Stop group removed entirely.
    assert "companyAnnouncements" not in data
    assert "Stop" not in data.get("hooks", {})
    # No surviving hook anywhere still invokes the legacy product-hook.
    for groups in data.get("hooks", {}).values():
        for group in groups:
            for h in group.get("hooks", []):
                assert "product-hook" not in h.get("command", "")
    # USER hooks preserved (the co-located SessionStart user group + PreToolUse).
    assert "SessionStart" in data["hooks"]
    assert data["hooks"]["PreToolUse"][0]["hooks"][0]["command"] == "my-own-guard.sh"
    # USER permissions preserved.
    assert data["permissions"] == {"allow": ["Bash(npm test:*)"]}
    # Install reference added, pinned to ref:main + autoUpdate (design §8/§5b).
    mkt = data["extraKnownMarketplaces"]["prawduct"]
    assert mkt["source"] == {"source": "github", "repo": "brookstalley/prawduct", "ref": "main"}
    assert mkt["autoUpdate"] is True
    assert data["enabledPlugins"]["prawduct@prawduct"] is True


def test_settings_preserves_other_marketplaces_and_plugins(repo: Path):
    # A repo that already references another marketplace/plugin keeps them.
    settings = repo / ".claude" / "settings.json"
    data = json.loads(settings.read_text())
    data["extraKnownMarketplaces"] = {"other": {"source": {"source": "github", "repo": "x/y"}}}
    data["enabledPlugins"] = {"other@other": True}
    settings.write_text(json.dumps(data, indent=2) + "\n")

    run_migrate(repo, "--apply")
    data = json.loads(settings.read_text())
    assert "other" in data["extraKnownMarketplaces"]
    assert "prawduct" in data["extraKnownMarketplaces"]
    assert data["enabledPlugins"]["other@other"] is True
    assert data["enabledPlugins"]["prawduct@prawduct"] is True


